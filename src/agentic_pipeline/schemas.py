    roi_margin_ratio: float = 0.35                              # Slack margin around piece to include neighboring parts
    neighbor_parts_included: int = 0
    edge_chamfer_score: float = 0.0
    silhouette_iou_score: float = 0.0
    color_match_score: float = 0.0
    stud_occlusion_score: float = 0.0
    neighbor_context_score: float = 0.0
    combined_visual_score: float = 0.0


