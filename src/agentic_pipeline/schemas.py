class FailureRootCause(str, Enum):
    """Causal taxonomy diagnosed by the GT Auditor Agent when a piece mismatches GT .io."""
    EXACT_MATCH = "EXACT_MATCH"
    IDENTIFIER_RECALL_MISS = "IDENTIFIER_RECALL_MISS"           # GT pose was never generated by Identifier
    GUARDIAN_FALSE_REJECTION = "GUARDIAN_FALSE_REJECTION"       # GT pose generated, but pruned by OBB/port tolerance
    PLACER_ROI_RANKING_ERROR = "PLACER_ROI_RANKING_ERROR"       # GT pose survived to Placer, but lost visually in ROI
    FLIP_OR_CALLOUT_DESYNC = "FLIP_OR_CALLOUT_DESYNC"           # Page rotation/flip or subassembly context missed
    UPSTREAM_CASCADE_ERROR = "UPSTREAM_CASCADE_ERROR"           # Parent piece in step t-k was misplaced, blocking GT


@dataclass
class StepContext:
    """Output of Agent 1 (Context & Camera Agent)."""
    page_num: int
    step_label: str
    is_flipped: bool = False
    is_callout_subassembly: bool = False
    subassembly_id: str = "main_model"
    camera_azimuth_deg: float = 45.0
    camera_elevation_deg: float = 30.0
    camera_scale: float = 2.65
    camera_offset: Tuple[float, float] = (200.0, 200.0)
    parts_to_place: List[Dict[str, Any]] = field(default_factory=list)
    crop_image_path: str = ""


