@dataclass
class AgenticPipelineReport:
    """Full execution report of the Multi-Agent Inference Pipeline on a set or corpus."""
    set_num: str
    pdf_path: str
    gt_io_path: Optional[str]
    output_io_path: str
    output_json_path: str
    model_routing: Dict[str, str]
    hardware_info: Dict[str, Any]
    total_steps: int = 0
    total_parts_placed: int = 0
    ground_parts_touching: int = 0
    physical_validity_rate: float = 100.0
    # Ground-Truth Evaluation Metrics (when gt_io_path is provided)
    gt_evaluated: bool = False
    total_parts_in_gt: int = 0
    first_attempt_exact_parts: int = 0
    first_attempt_accuracy_ratio: float = 0.0
    pct_parts_correct_before_fixes: float = 0.0
    pct_parts_correct_after_fixes: float = 0.0
    # Headline metric: excludes poses injected by teacher forcing from the GT
    pct_parts_correct_after_fixes_no_teacher_forcing: float = 0.0
    pct_edges_correct: float = 0.0
    convergence_depth: int = 0
    root_cause_breakdown: Dict[str, int] = field(default_factory=dict)
    fixes_proposed: List[ProposedFix] = field(default_factory=list)
    step_results: List[StepInferenceResult] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        def _sanitize(obj):
            if isinstance(obj, np.ndarray):
                return obj.tolist()
            if isinstance(obj, (np.floating, float)):
                return float(obj)
            if isinstance(obj, (np.integer, int)):
                return int(obj)
            if isinstance(obj, dict):
                return {k: _sanitize(v) for k, v in obj.items()}
            if isinstance(obj, (list, tuple)):
                return [_sanitize(v) for v in obj]
            return obj

        return _sanitize(asdict(self))
